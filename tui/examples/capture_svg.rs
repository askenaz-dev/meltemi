//! Captures the terminal surface as an SVG for the product site
//! (sitio-web-producto task 2.4).
//!
//! This is a **real** capture: it drives the same renderer the shell uses, over
//! a fixture session set standing in for a temporary repository driven by the
//! simulated agent. Nothing is drawn by hand, so the image cannot drift into a
//! mockup — regenerate it and the current UI is what appears. It carries no
//! personal path, no identity and no third-party product name (design D5).
//!
//! Usage: `cargo run -p meltemi --example capture_svg > docs/media/tui-sessions.svg`

use meltemi::shell::live::{LiveData, ProjectRow, SessionRow, Update};
use meltemi::shell::messages::Lang;
use meltemi::shell::present::{Presentation, PresentationEnv};
use meltemi::shell::render::{ConnState, ShellCtx, render};
use meltemi::shell::state::ShellState;
use meltemi_proto::SessionState;
use ratatui::Terminal;
use ratatui::backend::TestBackend;
use ratatui::style::{Color, Modifier};

const COLS: u16 = 96;
const ROWS: u16 = 24;
/// Monospace cell metrics of the SVG grid.
const CELL_W: f32 = 8.0;
const CELL_H: f32 = 18.0;

fn main() {
    let mut live = LiveData::new();
    live.apply(Update::Conn(ConnState::Connected {
        version: "0.1.0".into(),
        uptime_s: 1_845,
        sessions: 1,
    }));
    live.apply(Update::Pending(1));
    // Two fixture projects; the roots are deliberately generic.
    live.apply(Update::Projects(vec![
        ProjectRow {
            root: "/fixtures/harbour".into(),
            exists: true,
            sessions_total: 2,
            active_sessions: 1,
        },
        ProjectRow {
            root: "/fixtures/lighthouse".into(),
            exists: true,
            sessions_total: 1,
            active_sessions: 0,
        },
    ]));
    live.apply(Update::Sessions(vec![
        SessionRow {
            started_at: String::new(),
            ended_at: None,
            mode: None,
            model: None,
            id: "3f9c1a20".into(),
            agent: "mock-agent".into(),
            state: SessionState::Active,
            project_root: "/fixtures/harbour".into(),
            resumable: false,
            agent_id: Some("mock-agent".into()),
            profile: Some("work".into()),
            title: None,
        },
        SessionRow {
            started_at: String::new(),
            ended_at: None,
            mode: None,
            model: None,
            id: "7b21e4d8".into(),
            agent: "mock-agent".into(),
            state: SessionState::WaitingPermission,
            project_root: "/fixtures/harbour".into(),
            resumable: false,
            agent_id: Some("mock-agent".into()),
            profile: Some("personal".into()),
            title: None,
        },
        SessionRow {
            started_at: String::new(),
            ended_at: None,
            mode: None,
            model: None,
            id: "c04ab7f1".into(),
            agent: "mock-agent".into(),
            state: SessionState::Ended,
            project_root: "/fixtures/lighthouse".into(),
            resumable: true,
            agent_id: Some("mock-agent".into()),
            profile: None,
            title: None,
        },
    ]));

    let ctx = ShellCtx {
        present: Presentation::resolve(&PresentationEnv {
            lang: Some("en_US.UTF-8".into()),
            // A terminal with 24-bit colour, so the capture carries the brand's
            // exact blue (enfasis-con-color design D4).
            colorterm: Some("truecolor".into()),
            ..Default::default()
        }),
        lang: Lang::En,
        project: true,
        via: None,
    };
    let state = ShellState::new();

    let mut terminal = Terminal::new(TestBackend::new(COLS, ROWS)).expect("terminal");
    terminal
        .draw(|frame| render(frame, &state, &live, &ctx))
        .expect("draw");
    let buffer = terminal.backend().buffer().clone();

    let width = f32::from(COLS) * CELL_W;
    let height = f32::from(ROWS) * CELL_H;
    let mut svg = String::new();
    svg.push_str(&format!(
        concat!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {w} {h}\" ",
            "width=\"{w}\" height=\"{h}\" role=\"img\">\n",
            "  <!-- SPDX-License-Identifier: Apache-2.0 -->\n",
            // No `--` inside a comment: XML forbids it, and an SVG that is
            // not well-formed renders nowhere, the site included.
            "  <!-- GENERATED by `cargo run -p meltemi` (example `capture_svg`). ",
            "A real render of the terminal surface over fixture data; do not edit. -->\n",
            "  <style>\n",
            "    .bg {{ fill: #0b1220; }}\n",
            // Both text classes sit on the same cell grid, so both need the
            // monospace face: without it the reversed runs fall back to a
            // proportional serif and drift off their highlight.
            "    .fg, .revfg {{ font-family: var(--font-mono, ui-monospace, monospace); ",
            "font-size: 13px; white-space: pre; }}\n",
            "    .fg {{ fill: #e2e8f0; }}\n",
            "    .rev {{ fill: #e2e8f0; }}\n",
            "    .revfg {{ fill: #0b1220; }}\n",
            "  </style>\n",
            "  <rect class=\"bg\" x=\"0\" y=\"0\" width=\"{w}\" height=\"{h}\" rx=\"8\"/>\n"
        ),
        w = width,
        h = height
    ));

    for row in 0..ROWS {
        // Group the row into runs sharing one style (background, text colour,
        // bold, reverse video), so the banner, the selected row and the group
        // headers read in the image as they do in a terminal.
        let mut runs: Vec<(u16, String, RunStyle)> = Vec::new();
        for col in 0..COLS {
            let cell = &buffer[(col, row)];
            let style = RunStyle::of(cell.fg, cell.bg, cell.modifier);
            match runs.last_mut() {
                Some((_, text, run_style)) if *run_style == style => {
                    text.push_str(cell.symbol());
                }
                _ => runs.push((col, cell.symbol().to_string(), style)),
            }
        }
        let y = f32::from(row) * CELL_H;
        for (col, text, style) in runs {
            let block = style.reversed || style.bg.is_some();
            if text.trim().is_empty() && !block {
                continue;
            }
            let x = f32::from(col) * CELL_W;
            if block {
                let run_width = text.chars().count() as f32 * CELL_W;
                match &style.bg {
                    Some(bg) => svg.push_str(&format!(
                        "  <rect fill=\"{bg}\" x=\"{x}\" y=\"{y}\" width=\"{run_width}\" height=\"{CELL_H}\"/>\n"
                    )),
                    None => svg.push_str(&format!(
                        "  <rect class=\"rev\" x=\"{x}\" y=\"{y}\" width=\"{run_width}\" height=\"{CELL_H}\"/>\n"
                    )),
                }
            }
            let class = if style.reversed && style.bg.is_none() {
                "revfg"
            } else {
                "fg"
            };
            let fill = style
                .fg
                .as_ref()
                .map(|fg| format!(" fill=\"{fg}\""))
                .unwrap_or_default();
            let weight = if style.bold {
                " font-weight=\"700\""
            } else {
                ""
            };
            svg.push_str(&format!(
                "  <text class=\"{class}\"{fill}{weight} x=\"{x}\" y=\"{}\" xml:space=\"preserve\">{}</text>\n",
                y + CELL_H * 0.72,
                escape(&text)
            ));
        }
    }
    svg.push_str("</svg>\n");
    print!("{svg}");
}

/// The style of one run of cells, as the SVG tells it: colours as hex when the
/// cell has one, bold, and reverse video for a capture without colour.
#[derive(Clone, PartialEq, Eq)]
struct RunStyle {
    fg: Option<String>,
    bg: Option<String>,
    bold: bool,
    reversed: bool,
}

impl RunStyle {
    fn of(fg: Color, bg: Color, modifier: Modifier) -> Self {
        Self {
            fg: hex(fg),
            bg: hex(bg),
            bold: modifier.contains(Modifier::BOLD),
            reversed: modifier.contains(Modifier::REVERSED),
        }
    }
}

/// A cell colour as `#rrggbb`: the exact ones the renderer sets on a 24-bit
/// terminal, and the terminal's default (reset) as none.
fn hex(color: Color) -> Option<String> {
    match color {
        Color::Rgb(r, g, b) => Some(format!("#{r:02x}{g:02x}{b:02x}")),
        Color::White => Some("#ffffff".into()),
        _ => None,
    }
}

/// XML-escapes a run of text.
fn escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
